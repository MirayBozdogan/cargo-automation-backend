-- "Şifremi unuttum" bağlantıları. Bağlantıdaki anahtarın kendisi değil, yalnız SHA-256 özeti saklanır;
-- veritabanı okunsa bile bağlantı yeniden üretilemez.
CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash character varying(64) NOT NULL CONSTRAINT password_reset_tokens_token_hash_key UNIQUE,
    created_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    used_at timestamp with time zone
);

CREATE INDEX password_reset_tokens_user_id_idx ON password_reset_tokens (user_id);
