-- İlk şema: Hibernate'in mevcut entity'lerden ürettiği tablolarla birebir aynıdır.
-- Daha önce ddl-auto=update ile oluşmuş veritabanları bu sürümde "baseline" kabul edilir
-- ve bu dosya onlarda çalıştırılmaz (bkz. db/manual/README.md).

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean DEFAULT true NOT NULL,
    age integer,
    email character varying(255) CONSTRAINT users_email_key UNIQUE,
    name character varying(255),
    password character varying(255),
    role character varying(255),
    surname character varying(255),
    tc character varying(255) CONSTRAINT users_tc_key UNIQUE,
    tel_no character varying(255) CONSTRAINT users_tel_no_key UNIQUE
);

CREATE TABLE cities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100)
);

CREATE TABLE districts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id integer CONSTRAINT fk3g7x8w4lc7qxth7ibrr5j73mn REFERENCES cities(id),
    name character varying(100)
);

CREATE TABLE addresses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_no integer,
    building_no integer,
    city_id integer CONSTRAINT fk9fkb8qaj71tiyr9htkmn7r8y5 REFERENCES cities(id),
    district_id integer CONSTRAINT fkdu4j0drj57p0x9avyatpq2v5 REFERENCES districts(id),
    user_id integer CONSTRAINT fk1fa36y2oqhao3wgg2rw1pi459 REFERENCES users(id),
    neighborhood character varying(255)
);

CREATE TABLE prices (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_desi numeric(38,2),
    min_desi numeric(38,2),
    price numeric(38,2)
);

CREATE TABLE shipments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode character varying(12) NOT NULL CONSTRAINT shipments_barcode_key UNIQUE,
    status character varying(32) DEFAULT 'CREATED' NOT NULL
        CONSTRAINT shipments_status_check CHECK (status IN
            ('CREATED', 'ACCEPTED', 'READY_FOR_DISTRIBUTION', 'OUT_FOR_DELIVERY', 'DELIVERED')),
    deleted boolean NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    delivered_at timestamp(6) with time zone,
    sender_id integer CONSTRAINT fk4k10nlqhuye1k718glueny0v4 REFERENCES users(id),
    receiver_id integer CONSTRAINT fkn1h7ixi1xm7o5p3by2s3pmyal REFERENCES users(id),
    courier_id integer CONSTRAINT fk_shipments_courier REFERENCES users(id),
    sender_address_id integer,
    receiver_address_id integer,
    height numeric(38,2),
    length numeric(38,2),
    width numeric(38,2),
    weight numeric(38,2),
    price numeric(38,2),
    sender_name character varying(255),
    sender_surname character varying(255),
    sender_city character varying(255),
    sender_district character varying(255),
    sender_address_text character varying(255),
    receiver_name character varying(255),
    receiver_surname character varying(255),
    receiver_city character varying(255),
    receiver_district character varying(255),
    receiver_address_text character varying(255)
);

CREATE INDEX idx_shipments_courier ON shipments (courier_id);
